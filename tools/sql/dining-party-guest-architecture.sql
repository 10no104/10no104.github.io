  where guest.branch = normalized_branch
    and (
      (p_guest_id is not null and guest.id = p_guest_id)
      or
      (p_guest_id is null and normalized_code <> '' and guest.display_code = normalized_code)
    )
  order by guest.created_at desc
  limit 1;

  if not found then
    raise exception 'Guest not found';
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'table_id', table_record.id,
        'table_code', table_record.table_code,
        'qr_number', table_record.qr_number
      )
      order by table_record.table_code
    ),
    '[]'::jsonb
  )
  into party_tables
  from public.dining_party_tables as party_table
  join public.dining_tables as table_record
    on table_record.id = party_table.table_id
  where party_table.party_id = target_guest.party_id;

  select
    coalesce(
      jsonb_agg(to_jsonb(order_row) order by order_row.created_at desc),
      '[]'::jsonb
    ),
    coalesce(sum(order_row.total) filter (
      where order_row.kind = 'order'
        and order_row.status <> 'canceled'
    ), 0)
  into guest_orders, guest_total
  from (
    select
      request.id,
      request.table_id,
      request.table_code,
      request.kind,
      request.request_type,
      request.status,
      request.items,
      request.item_count,
      request.subtotal,
      request.tax,
      request.total,
      request.note,
      request.created_at,
      request.updated_at
    from public.dining_requests as request
    where request.guest_id = target_guest.id
    order by request.created_at desc
  ) as order_row;

  return jsonb_build_object(
    'guest', to_jsonb(target_guest),
    'party_id', target_guest.party_id,
    'tables', party_tables,
    'orders', guest_orders,
    'total', guest_total
  );
end;
$$;

create or replace function public.mark_dining_guest_paid(
  p_branch text,
  p_display_code text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  target_guest public.dining_guests;
begin
  select guest.*
  into target_guest
  from public.dining_guests as guest
  where guest.branch = lower(trim(p_branch))
    and guest.display_code = upper(trim(p_display_code))
    and guest.status = 'ACTIVE'
  order by guest.created_at desc
  limit 1
  for update;

  if not found then
    raise exception 'Active Guest not found';
  end if;

  update public.dining_guests
  set status = 'PAID',
      paid_at = now(),
      last_seen_at = now()
  where id = target_guest.id;

  insert into public.dining_guest_events (guest_id, event_type, detail)
  values (
    target_guest.id,
    'PAID',
    jsonb_build_object('display_code', target_guest.display_code)
  );

  return public.lookup_dining_guest_bill(
    lower(trim(p_branch)),
    target_guest.id,
    null
  );
end;
$$;

-- Seed permanent Table/QR mappings from the current active sessions.
insert into public.dining_tables (branch, table_code, qr_number)
select
  session.branch,
  session.table_code,
  session.qr_number
from public.dining_qr_sessions as session
where session.status = 'active'
  and nullif(trim(session.table_code), '') is not null
on conflict (branch, table_code)
do update set qr_number = excluded.qr_number;

-- Preserve current service by converting each pre-migration active table
-- session into a one-table Party.
do $$
declare
  session_record record;
  migrated_party_id bigint;
  migrated_table_id bigint;
begin
  for session_record in
    select
      session.branch,
      session.qr_number,
      session.table_code
    from public.dining_qr_sessions as session
    where session.status = 'active'
      and nullif(trim(session.table_code), '') is not null
  loop
    select table_record.id, table_record.current_party_id
    into migrated_table_id, migrated_party_id
    from public.dining_tables as table_record
    where table_record.branch = session_record.branch
      and lower(table_record.table_code) = lower(session_record.table_code)
    for update;

    if migrated_party_id is null then
      insert into public.dining_parties (branch)
      values (session_record.branch)
      returning id into migrated_party_id;

      update public.dining_tables
      set current_party_id = migrated_party_id
      where id = migrated_table_id;

      insert into public.dining_party_tables (party_id, table_id)
      values (migrated_party_id, migrated_table_id);
    end if;
  end loop;
end;
$$;

