create or replace function public.create_dining_guest_display_code(
  p_branch text
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  candidate text;
  attempt integer;
begin
  for attempt in 1..80 loop
    candidate :=
      substr(alphabet, 1 + floor(random() * length(alphabet))::integer, 1)
      || substr(alphabet, 1 + floor(random() * length(alphabet))::integer, 1)
      || substr(alphabet, 1 + floor(random() * length(alphabet))::integer, 1)
      || substr(alphabet, 1 + floor(random() * length(alphabet))::integer, 1);

    if not exists (
      select 1
      from public.dining_guests as guest
      where guest.branch = p_branch
        and guest.display_code = candidate
    ) then
      return candidate;
    end if;
  end loop;

  raise exception 'Could not allocate a guest display code';
end;
$$;

create or replace function public.assign_dining_table_qr(
  p_branch text,
  p_table_code text,
  p_qr_number integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_branch text := lower(trim(p_branch));
  normalized_table_code text := trim(p_table_code);
  target_table public.dining_tables;
  conflicting_table public.dining_tables;
begin
  if normalized_branch is null or normalized_branch !~ '^[a-z0-9_-]{1,40}$' then
    raise exception 'Invalid branch';
  end if;
  if normalized_table_code is null or char_length(normalized_table_code) not between 1 and 40 then
    raise exception 'Invalid table code';
  end if;
  if p_qr_number is null or p_qr_number not between 1 and 10 then
    raise exception 'Invalid QR number';
  end if;

  perform pg_advisory_xact_lock(hashtext('table-qr:' || normalized_branch));

  select table_record.*
  into target_table
  from public.dining_tables as table_record
  where table_record.branch = normalized_branch
    and lower(table_record.table_code) = lower(normalized_table_code)
  for update;

  if found and target_table.current_party_id is not null then
    raise exception 'Table % belongs to an active party', target_table.table_code;
  end if;

  select table_record.*
  into conflicting_table
  from public.dining_tables as table_record
  where table_record.branch = normalized_branch
    and table_record.qr_number = p_qr_number
    and lower(table_record.table_code) <> lower(normalized_table_code)
  for update;

  if found then
    if conflicting_table.current_party_id is not null then
      raise exception 'QR % belongs to an active party at Table %', p_qr_number, conflicting_table.table_code;
    end if;
    update public.dining_tables
    set qr_number = null
    where id = conflicting_table.id;
  end if;

  if target_table.id is null then
    insert into public.dining_tables (branch, table_code, qr_number)
    values (normalized_branch, normalized_table_code, p_qr_number)
    returning * into target_table;
  else
    update public.dining_tables
    set qr_number = p_qr_number
    where id = target_table.id
    returning * into target_table;
  end if;

  update public.dining_qr_sessions
  set status = 'closed',
      ended_at = coalesce(ended_at, now()),
      ended_reason = 'permanent-table-qr-remap'
  where branch = normalized_branch
    and status = 'active'
    and (
      qr_number = p_qr_number
      or lower(table_code) = lower(normalized_table_code)
    );

  return jsonb_build_object(
    'id', target_table.id,
    'branch', target_table.branch,
    'table_code', target_table.table_code,
    'qr_number', target_table.qr_number,
    'current_party_id', target_table.current_party_id
  );
end;
$$;

create or replace function public.start_dining_party(
  p_branch text,
  p_table_codes text[]
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_branch text := lower(trim(p_branch));
  normalized_codes text[];
  new_party public.dining_parties;
  selected_count integer;
  code_count integer;
begin
  if normalized_branch is null or normalized_branch !~ '^[a-z0-9_-]{1,40}$' then
    raise exception 'Invalid branch';
  end if;

  select array_agg(distinct trim(selected.code))
  into normalized_codes
  from unnest(coalesce(p_table_codes, array[]::text[])) as selected(code)
  where nullif(trim(selected.code), '') is not null;

  code_count := coalesce(array_length(normalized_codes, 1), 0);
  if code_count < 1 or code_count > 30 then
    raise exception 'Select between 1 and 30 tables';
  end if;

  perform pg_advisory_xact_lock(hashtext('party:' || normalized_branch));

  select count(*)
  into selected_count
  from public.dining_tables as table_record
  where table_record.branch = normalized_branch
    and lower(table_record.table_code) = any (
      select lower(selected.code) from unnest(normalized_codes) as selected(code)
    )
    and table_record.qr_number is not null
    and table_record.current_party_id is null;

  if selected_count <> code_count then
    raise exception 'Every selected table needs an assigned QR and must be available';
  end if;

  insert into public.dining_parties (branch)
  values (normalized_branch)
  returning * into new_party;

  update public.dining_tables
  set current_party_id = new_party.id
  where branch = normalized_branch
    and lower(table_code) = any (
      select lower(selected.code) from unnest(normalized_codes) as selected(code)
    );

  insert into public.dining_party_tables (party_id, table_id)
  select new_party.id, table_record.id
  from public.dining_tables as table_record
  where table_record.current_party_id = new_party.id;

  update public.dining_qr_sessions
  set status = 'closed',
      ended_at = coalesce(ended_at, now()),
      ended_reason = 'party-restarted'
  where branch = normalized_branch
    and status = 'active'
    and (
      qr_number in (
        select table_record.qr_number
        from public.dining_tables as table_record
        where table_record.current_party_id = new_party.id
      )
      or lower(table_code) in (
        select lower(table_record.table_code)
        from public.dining_tables as table_record
        where table_record.current_party_id = new_party.id
      )
    );

  insert into public.dining_qr_sessions (branch, qr_number, table_code)
  select table_record.branch, table_record.qr_number, table_record.table_code
  from public.dining_tables as table_record
  where table_record.current_party_id = new_party.id;

  return jsonb_build_object(
    'party_id', new_party.id,
    'status', new_party.status,
    'created_at', new_party.created_at,
    'table_codes', normalized_codes
  );
end;
$$;

create or replace function public.add_dining_tables_to_party(
  p_branch text,
  p_party_id bigint,
  p_table_codes text[]
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_branch text := lower(trim(p_branch));
  normalized_codes text[];
  active_party public.dining_parties;
  selected_count integer;
  code_count integer;
begin
  select party.*
  into active_party
  from public.dining_parties as party
  where party.id = p_party_id
    and party.branch = normalized_branch
    and party.status = 'ACTIVE'
  for update;

  if not found then
    raise exception 'Active party not found';
  end if;

  select array_agg(distinct trim(selected.code))
  into normalized_codes
  from unnest(coalesce(p_table_codes, array[]::text[])) as selected(code)
  where nullif(trim(selected.code), '') is not null;

  code_count := coalesce(array_length(normalized_codes, 1), 0);
  if code_count < 1 or code_count > 30 then
    raise exception 'Select between 1 and 30 tables';
  end if;

  perform pg_advisory_xact_lock(hashtext('party:' || normalized_branch));

  select count(*)
  into selected_count
  from public.dining_tables as table_record
  where table_record.branch = normalized_branch
    and lower(table_record.table_code) = any (
      select lower(selected.code) from unnest(normalized_codes) as selected(code)
    )
    and table_record.qr_number is not null
    and table_record.current_party_id is null;

  if selected_count <> code_count then
    raise exception 'Every selected table needs an assigned QR and must be available';
  end if;

  update public.dining_tables
  set current_party_id = active_party.id
  where branch = normalized_branch
    and lower(table_code) = any (
      select lower(selected.code) from unnest(normalized_codes) as selected(code)
    );

  insert into public.dining_party_tables (party_id, table_id)
  select active_party.id, table_record.id
  from public.dining_tables as table_record
  where table_record.current_party_id = active_party.id
    and lower(table_record.table_code) = any (
      select lower(selected.code) from unnest(normalized_codes) as selected(code)
    );

  insert into public.dining_qr_sessions (branch, qr_number, table_code)
  select table_record.branch, table_record.qr_number, table_record.table_code
  from public.dining_tables as table_record
  where table_record.current_party_id = active_party.id
    and lower(table_record.table_code) = any (
      select lower(selected.code) from unnest(normalized_codes) as selected(code)
    );

  return jsonb_build_object(
    'party_id', active_party.id,
    'table_codes', normalized_codes
  );
end;
$$;

create or replace function public.close_dining_party(
  p_branch text,
  p_party_id bigint,
  p_reason text default 'table-checkout'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_branch text := lower(trim(p_branch));
  active_party public.dining_parties;
begin
  select party.*
  into active_party
  from public.dining_parties as party
  where party.id = p_party_id
    and party.branch = normalized_branch
    and party.status = 'ACTIVE'
  for update;

  if not found then
    raise exception 'Active party not found';
  end if;

  update public.dining_qr_sessions as session
  set status = 'closed',
      ended_at = coalesce(session.ended_at, now()),
      ended_reason = left(coalesce(nullif(trim(p_reason), ''), 'party-closed'), 80)
  where session.branch = normalized_branch
    and session.status = 'active'
    and exists (
      select 1
      from public.dining_tables as table_record
      where table_record.current_party_id = active_party.id
        and (
          table_record.qr_number = session.qr_number
          or lower(table_record.table_code) = lower(session.table_code)
        )
    );

  update public.dining_requests
  set status = 'canceled'
  where party_id = active_party.id
    and status not in ('completed', 'canceled');

  update public.dining_guests
  set status = 'EXPIRED',
      expires_at = greatest(created_at + interval '1 second', now())
  where party_id = active_party.id
    and status = 'ACTIVE';

  insert into public.dining_guest_events (guest_id, event_type, detail)
  select guest.id, 'EXPIRED', jsonb_build_object('reason', 'party-closed')
  from public.dining_guests as guest
  where guest.party_id = active_party.id
    and guest.status = 'EXPIRED'
    and not exists (
      select 1
      from public.dining_guest_events as event
      where event.guest_id = guest.id
        and event.event_type = 'EXPIRED'
    );

  update public.dining_party_tables
  set left_at = now()
  where party_id = active_party.id
    and left_at is null;

  update public.dining_tables
  set current_party_id = null
  where current_party_id = active_party.id;

  update public.dining_parties
  set status = 'CLOSED',
      closed_at = now(),
      closed_reason = left(coalesce(nullif(trim(p_reason), ''), 'party-closed'), 80)
  where id = active_party.id;

  return jsonb_build_object(
    'party_id', active_party.id,
    'status', 'CLOSED'
  );
end;
$$;

create or replace function public.resolve_dining_guest(
  p_branch text,
  p_qr_number integer,
  p_guest_id uuid default null,
  p_device_info jsonb default '{}'::jsonb,
  p_current_page text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_branch text := lower(trim(p_branch));
  active_table public.dining_tables;
  active_party public.dining_parties;
  resolved_guest public.dining_guests;
  compatibility_session_id bigint;
  safe_device_info jsonb := coalesce(p_device_info, '{}'::jsonb);
  safe_page text := left(coalesce(p_current_page, ''), 300);
begin
  if normalized_branch is null or normalized_branch !~ '^[a-z0-9_-]{1,40}$' then
    raise exception 'Invalid branch';
  end if;
  if p_qr_number is null or p_qr_number not between 1 and 10 then
    raise exception 'Invalid QR number';
  end if;
  if jsonb_typeof(safe_device_info) <> 'object'
    or octet_length(safe_device_info::text) > 12000
  then
    safe_device_info := '{}'::jsonb;
  end if;

  update public.dining_guests
  set status = 'EXPIRED'
  where status = 'ACTIVE'
    and expires_at <= now();

  select table_record.*
  into active_table
  from public.dining_tables as table_record
  join public.dining_parties as party
    on party.id = table_record.current_party_id
   and party.status = 'ACTIVE'
  where table_record.branch = normalized_branch
    and table_record.qr_number = p_qr_number
  limit 1;

  if not found then
    raise exception 'This QR is not assigned to an active party';
  end if;

  select party.*
  into active_party
  from public.dining_parties as party
  where party.id = active_table.current_party_id
    and party.status = 'ACTIVE';

  if p_guest_id is not null then
    select guest.*
    into resolved_guest
    from public.dining_guests as guest
    where guest.id = p_guest_id
      and guest.branch = normalized_branch
      and guest.party_id = active_party.id
      and guest.status = 'ACTIVE'
      and guest.expires_at > now()
    for update;
  end if;

  if resolved_guest.id is null then
    insert into public.dining_guests (
      branch,
      display_code,
      party_id,
      current_table_id,
      device_info,
      current_page
    )
    values (
      normalized_branch,
      public.create_dining_guest_display_code(normalized_branch),
      active_party.id,
      active_table.id,
      safe_device_info,
      safe_page
    )
    returning * into resolved_guest;

    insert into public.dining_guest_events (guest_id, event_type, detail)
    values (
      resolved_guest.id,
      'CREATED',
      jsonb_build_object(
        'party_id', active_party.id,
        'table_id', active_table.id,
        'table_code', active_table.table_code
      )
    );
  else
    if resolved_guest.current_page is distinct from safe_page then
      insert into public.dining_guest_events (guest_id, event_type, detail)
      values (
        resolved_guest.id,
        'PAGE_CHANGED',
        jsonb_build_object(
          'from', resolved_guest.current_page,
          'to', safe_page,
          'table_code', active_table.table_code
        )
      );
    end if;

    update public.dining_guests
    set last_seen_at = now(),
        current_table_id = active_table.id,
        current_page = safe_page,
        device_info = case
          when safe_device_info = '{}'::jsonb then device_info
          else safe_device_info
        end
    where id = resolved_guest.id
    returning * into resolved_guest;
  end if;

  select session.id
  into compatibility_session_id
  from public.dining_qr_sessions as session
  where session.branch = normalized_branch
    and session.qr_number = p_qr_number
    and session.status = 'active'
  order by session.started_at desc
  limit 1;

  return jsonb_build_object(
    'guest_id', resolved_guest.id,
    'display_code', resolved_guest.display_code,
    'guest_status', resolved_guest.status,
    'created_at', resolved_guest.created_at,
    'expires_at', resolved_guest.expires_at,
    'party_id', active_party.id,
    'party_status', active_party.status,
    'table_id', active_table.id,
    'table_code', active_table.table_code,
    'qr_number', active_table.qr_number,
    'qr_session_id', compatibility_session_id
  );
end;
$$;

