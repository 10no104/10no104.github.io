create or replace function public.submit_dining_request_v2(
  p_branch text,
  p_qr_number integer,
  p_guest_id uuid,
  p_kind text,
  p_request_type text,
  p_note text default '',
  p_items jsonb default '[]'::jsonb
)
returns public.dining_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_branch text := lower(trim(p_branch));
  normalized_kind text := lower(trim(p_kind));
  normalized_request_type text := lower(trim(p_request_type));
  active_guest public.dining_guests;
  active_table public.dining_tables;
  new_request public.dining_requests;
  compatibility_session_id bigint;
  calculated_item_count integer := 0;
  calculated_subtotal numeric(10, 2) := 0;
  calculated_tax numeric(10, 2) := 0;
  calculated_total numeric(10, 2) := 0;
begin
  if normalized_branch is null or normalized_branch !~ '^[a-z0-9_-]{1,40}$' then
    raise exception 'Invalid branch';
  end if;
  if p_guest_id is null then
    raise exception 'Guest is required';
  end if;
  if p_qr_number is null or p_qr_number not between 1 and 10 then
    raise exception 'Invalid QR number';
  end if;
  if normalized_kind is null or normalized_kind not in ('order', 'service') then
    raise exception 'Invalid request kind';
  end if;
  if normalized_request_type is null or normalized_request_type not in ('order', 'water', 'napkins', 'server') then
    raise exception 'Invalid request type';
  end if;
  if p_items is null
    or jsonb_typeof(p_items) <> 'array'
    or jsonb_array_length(p_items) > 60
    or octet_length(p_items::text) > 120000
  then
    raise exception 'Invalid order items';
  end if;

  select guest.*
  into active_guest
  from public.dining_guests as guest
  join public.dining_parties as party
    on party.id = guest.party_id
   and party.status = 'ACTIVE'
  where guest.id = p_guest_id
    and guest.branch = normalized_branch
    and guest.status = 'ACTIVE'
    and guest.expires_at > now()
  for update;

  if not found then
    raise exception 'Guest is no longer active';
  end if;

  select table_record.*
  into active_table
  from public.dining_tables as table_record
  where table_record.branch = normalized_branch
    and table_record.qr_number = p_qr_number
    and table_record.current_party_id = active_guest.party_id;

  if not found then
    raise exception 'This Table does not belong to the Guest Party';
  end if;

  if normalized_kind = 'order' then
    if normalized_request_type <> 'order' or jsonb_array_length(p_items) < 1 then
      raise exception 'An order requires one or more menu items';
    end if;

    if exists (
      select 1
      from jsonb_array_elements(p_items) as element(item)
      where nullif(trim(element.item->>'menuId'), '') is null
        or coalesce(element.item->>'quantity', '') !~ '^[0-9]+$'
        or (element.item->>'quantity')::integer not between 1 and 50
        or coalesce(element.item->>'unitPrice', '') !~ '^[0-9]+([.][0-9]{1,2})?$'
        or (element.item->>'unitPrice')::numeric < 0
        or (element.item->>'unitPrice')::numeric > 9999.99
    ) then
      raise exception 'One or more menu items are invalid';
    end if;

    select
      coalesce(sum((element.item->>'quantity')::integer), 0),
      coalesce(sum(
        (element.item->>'quantity')::integer
        * (element.item->>'unitPrice')::numeric
      ), 0)
    into calculated_item_count, calculated_subtotal
    from jsonb_array_elements(p_items) as element(item);

    calculated_subtotal := round(calculated_subtotal, 2);
    calculated_tax := round(calculated_subtotal * 0.13, 2);
    calculated_total := calculated_subtotal + calculated_tax;
    if calculated_item_count > 100 then
      raise exception 'An order cannot contain more than 100 items';
    end if;
  else
    if normalized_request_type = 'order' or jsonb_array_length(p_items) <> 0 then
      raise exception 'A service request cannot contain menu items';
    end if;
  end if;

  select session.id
  into compatibility_session_id
  from public.dining_qr_sessions as session
  where session.branch = normalized_branch
    and session.qr_number = p_qr_number
    and session.status = 'active'
  order by session.started_at desc
  limit 1;

  insert into public.dining_requests (
    branch,
    table_code,
    guest_count,
    kind,
    request_type,
    status,
    source,
    qr_number,
    qr_session_id,
    party_id,
    guest_id,
    table_id,
    added_by,
    note,
    items,
    item_count,
    subtotal,
    tax,
    total
  )
  values (
    normalized_branch,
    active_table.table_code,
    1,
    normalized_kind,
    normalized_request_type,
    'new',
    case when normalized_kind = 'order' then 'table-qr' else 'table-service-call' end,
    p_qr_number,
    compatibility_session_id,
    active_guest.party_id,
    active_guest.id,
    active_table.id,
    'guest',
    left(coalesce(p_note, ''), 1000),
    p_items,
    calculated_item_count,
    calculated_subtotal,
    calculated_tax,
    calculated_total
  )
  returning * into new_request;

  if normalized_kind = 'order' then
    insert into public.dining_order_items (
      request_id,
      guest_id,
      party_id,
      table_id,
      menu_id,
      name_ko,
      name_en,
      quantity,
      unit_price,
      line_total,
      note
    )
    select
      new_request.id,
      active_guest.id,
      active_guest.party_id,
      active_table.id,
      left(trim(element.item->>'menuId'), 120),
      left(coalesce(element.item->>'nameKo', ''), 200),
      left(coalesce(element.item->>'nameEn', ''), 200),
      (element.item->>'quantity')::integer,
      round((element.item->>'unitPrice')::numeric, 2),
      round(
        (element.item->>'quantity')::integer
        * (element.item->>'unitPrice')::numeric,
        2
      ),
      left(coalesce(element.item->>'note', ''), 500)
    from jsonb_array_elements(p_items) as element(item);
  end if;

  insert into public.dining_order_events (
    request_id,
    event_type,
    next_value,
    actor
  )
  values (
    new_request.id,
    'CREATED',
    jsonb_build_object(
      'status', new_request.status,
      'table_id', active_table.id,
      'table_code', active_table.table_code,
      'guest_id', active_guest.id
    ),
    'guest'
  );

  update public.dining_guests
  set last_seen_at = now(),
      current_page = '/test/menu/'
  where id = active_guest.id;

  return new_request;
end;
$$;

create or replace function public.sync_dining_order_status_and_notify()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  notification_type text;
  notification_title text;
  notification_message text;
begin
  if new.status is not distinct from old.status then
    return new;
  end if;

  update public.dining_order_items
  set status = new.status
  where request_id = new.id;

  insert into public.dining_order_events (
    request_id,
    event_type,
    previous_value,
    next_value,
    actor
  )
  values (
    new.id,
    case when new.status = 'canceled' then 'CANCELED' else 'STATUS_CHANGED' end,
    jsonb_build_object('status', old.status),
    jsonb_build_object('status', new.status),
    'staff'
  );

  if new.guest_id is not null then
    if new.status in ('acknowledged', 'preparing') then
      notification_type := 'COOKING';
      notification_title := case when new.kind = 'order' then 'Order accepted' else 'Staff is coming' end;
      notification_message := case when new.kind = 'order' then 'Your order is being prepared.' else 'A staff member is on the way.' end;
    elsif new.status = 'ready' then
      notification_type := 'READY';
      notification_title := 'Order ready';
      notification_message := 'Your order is ready.';
    elsif new.status = 'completed' then
      notification_type := 'ORDER_SERVED';
      notification_title := case when new.kind = 'order' then 'Order served' else 'Request completed' end;
      notification_message := case when new.kind = 'order' then 'This order has been served.' else 'Your request has been completed.' end;
    elsif new.status = 'canceled' then
      notification_type := 'ITEM_UNAVAILABLE';
      notification_title := 'Order update';
      notification_message := 'Please ask a staff member about this canceled request.';
    end if;

    if notification_type is not null then
      insert into public.dining_notifications (
        branch,
        party_id,
        guest_id,
        table_id,
        request_id,
        notification_type,
        title,
        message
      )
      values (
        new.branch,
        new.party_id,
        new.guest_id,
        new.table_id,
        new.id,
        notification_type,
        notification_title,
        notification_message
      );
    end if;
  end if;

  return new;
end;
$$;

