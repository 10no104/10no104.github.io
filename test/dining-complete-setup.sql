create or replace function public.create_dining_guest_display_code(
  p_branch text
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  candidate text;
  attempt integer;
begin
  for attempt in 1..80 loop
    candidate :=
      substr(alphabet, 1 + floor(random() * length(alphabet))::integer, 1)
      || substr(alphabet, 1 + floor(random() * length(alphabet))::integer, 1)
      || substr(alphabet, 1 + floor(random() * length(alphabet))::integer, 1)
      || substr(alphabet, 1 + floor(random() * length(alphabet))::integer, 1);

    if not exists (
      select 1
      from public.dining_guests as guest
      where guest.branch = p_branch
        and guest.display_code = candidate
    ) then
      return candidate;
    end if;
  end loop;

  raise exception 'Could not allocate a guest display code';
end;
$$;

create or replace function public.assign_dining_table_qr(
  p_branch text,
  p_table_code text,
  p_qr_number integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_branch text := lower(trim(p_branch));
  normalized_table_code text := trim(p_table_code);
  target_table public.dining_tables;
  conflicting_table public.dining_tables;
begin
  if normalized_branch is null or normalized_branch !~ '^[a-z0-9_-]{1,40}$' then
    raise exception 'Invalid branch';
  end if;
  if normalized_table_code is null or char_length(normalized_table_code) not between 1 and 40 then
    raise exception 'Invalid table code';
  end if;
  if p_qr_number is null or p_qr_number not between 1 and 10 then
    raise exception 'Invalid QR number';
  end if;

  perform pg_advisory_xact_lock(hashtext('table-qr:' || normalized_branch));

  select table_record.*
  into target_table
  from public.dining_tables as table_record
  where table_record.branch = normalized_branch
    and lower(table_record.table_code) = lower(normalized_table_code)
  for update;

  if found and target_table.current_party_id is not null then
    raise exception 'Table % belongs to an active party', target_table.table_code;
  end if;

  select table_record.*
  into conflicting_table
  from public.dining_tables as table_record
  where table_record.branch = normalized_branch
    and table_record.qr_number = p_qr_number
    and lower(table_record.table_code) <> lower(normalized_table_code)
  for update;

  if found then
    if conflicting_table.current_party_id is not null then
      raise exception 'QR % belongs to an active party at Table %', p_qr_number, conflicting_table.table_code;
    end if;
    update public.dining_tables
    set qr_number = null
    where id = conflicting_table.id;
  end if;

  if target_table.id is null then
    insert into public.dining_tables (branch, table_code, qr_number)
    values (normalized_branch, normalized_table_code, p_qr_number)
    returning * into target_table;
  else
    update public.dining_tables
    set qr_number = p_qr_number
    where id = target_table.id
    returning * into target_table;
  end if;

  update public.dining_qr_sessions
  set status = 'closed',
      ended_at = coalesce(ended_at, now()),
      ended_reason = 'permanent-table-qr-remap'
  where branch = normalized_branch
    and status = 'active'
    and (
      qr_number = p_qr_number
      or lower(table_code) = lower(normalized_table_code)
    );

  return jsonb_build_object(
    'id', target_table.id,
    'branch', target_table.branch,
    'table_code', target_table.table_code,
    'qr_number', target_table.qr_number,
    'current_party_id', target_table.current_party_id
  );
end;
$$;

create or replace function public.start_dining_party(
  p_branch text,
  p_table_codes text[]
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_branch text := lower(trim(p_branch));
  normalized_codes text[];
  new_party public.dining_parties;
  selected_count integer;
  code_count integer;
begin
  if normalized_branch is null or normalized_branch !~ '^[a-z0-9_-]{1,40}$' then
    raise exception 'Invalid branch';
  end if;

  select array_agg(distinct trim(selected.code))
  into normalized_codes
  from unnest(coalesce(p_table_codes, array[]::text[])) as selected(code)
  where nullif(trim(selected.code), '') is not null;

  code_count := coalesce(array_length(normalized_codes, 1), 0);
  if code_count < 1 or code_count > 30 then
    raise exception 'Select between 1 and 30 tables';
  end if;

  perform pg_advisory_xact_lock(hashtext('party:' || normalized_branch));

  select count(*)
  into selected_count
  from public.dining_tables as table_record
  where table_record.branch = normalized_branch
    and lower(table_record.table_code) = any (
      select lower(selected.code) from unnest(normalized_codes) as selected(code)
    )
    and table_record.qr_number is not null
    and table_record.current_party_id is null;

  if selected_count <> code_count then
    raise exception 'Every selected table needs an assigned QR and must be available';
  end if;

  insert into public.dining_parties (branch)
  values (normalized_branch)
  returning * into new_party;

  update public.dining_tables
  set current_party_id = new_party.id
  where branch = normalized_branch
    and lower(table_code) = any (
      select lower(selected.code) from unnest(normalized_codes) as selected(code)
    );

  insert into public.dining_party_tables (party_id, table_id)
  select new_party.id, table_record.id
  from public.dining_tables as table_record
  where table_record.current_party_id = new_party.id;

  update public.dining_qr_sessions
  set status = 'closed',
      ended_at = coalesce(ended_at, now()),
      ended_reason = 'party-restarted'
  where branch = normalized_branch
    and status = 'active'
    and (
      qr_number in (
        select table_record.qr_number
        from public.dining_tables as table_record
        where table_record.current_party_id = new_party.id
      )
      or lower(table_code) in (
        select lower(table_record.table_code)
        from public.dining_tables as table_record
        where table_record.current_party_id = new_party.id
      )
    );

  insert into public.dining_qr_sessions (branch, qr_number, table_code)
  select table_record.branch, table_record.qr_number, table_record.table_code
  from public.dining_tables as table_record
  where table_record.current_party_id = new_party.id;

  return jsonb_build_object(
    'party_id', new_party.id,
    'status', new_party.status,
    'created_at', new_party.created_at,
    'table_codes', normalized_codes
  );
end;
$$;

