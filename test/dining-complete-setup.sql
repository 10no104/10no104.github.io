create or replace function public.lookup_dining_guest_bill(
  p_branch text,
  p_guest_id uuid default null,
  p_display_code text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_branch text := lower(trim(p_branch));
  normalized_code text := upper(trim(coalesce(p_display_code, '')));
  target_guest public.dining_guests;
  party_tables jsonb;
  guest_orders jsonb;
  guest_total numeric(10, 2);
begin
  select guest.*
  into target_guest
  from public.dining_guests as guest
  where guest.branch = normalized_branch
    and (
      (p_guest_id is not null and guest.id = p_guest_id)
