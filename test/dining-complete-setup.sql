-- Seed permanent Table/QR mappings from the current active sessions.
insert into public.dining_tables (branch, table_code, qr_number)
select
  session.branch,
  session.table_code,
  session.qr_number
from public.dining_qr_sessions as session
where session.status = 'active'
  and nullif(trim(session.table_code), '') is not null
on conflict (branch, table_code)
do update set qr_number = excluded.qr_number;

-- Preserve current service by converting each pre-migration active table
-- session into a one-table Party.
do $$
declare
  session_record record;
  migrated_party_id bigint;
  migrated_table_id bigint;
begin
  for session_record in
    select
      session.branch,
      session.qr_number,
      session.table_code
    from public.dining_qr_sessions as session
    where session.status = 'active'
      and nullif(trim(session.table_code), '') is not null
  loop
    select table_record.id, table_record.current_party_id
    into migrated_table_id, migrated_party_id
    from public.dining_tables as table_record
    where table_record.branch = session_record.branch
      and lower(table_record.table_code) = lower(session_record.table_code)
    for update;

    if migrated_party_id is null then
      insert into public.dining_parties (branch)
      values (session_record.branch)
      returning id into migrated_party_id;

      update public.dining_tables
      set current_party_id = migrated_party_id
      where id = migrated_table_id;

      insert into public.dining_party_tables (party_id, table_id)
      values (migrated_party_id, migrated_table_id);
    end if;
  end loop;
end;
$$;

