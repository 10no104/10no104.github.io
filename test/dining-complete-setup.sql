      request.table_id,
      request.table_code,
      request.kind,
      request.request_type,
      request.status,
      request.items,
      request.item_count,
      request.subtotal,
      request.tax,
      request.total,
      request.note,
      request.created_at,
      request.updated_at
    from public.dining_requests as request
    where request.guest_id = target_guest.id
    order by request.created_at desc
  ) as order_row;

  return jsonb_build_object(
    'guest', to_jsonb(target_guest),
    'party_id', target_guest.party_id,
    'tables', party_tables,
    'orders', guest_orders,
    'total', guest_total
  );
end;
$$;

