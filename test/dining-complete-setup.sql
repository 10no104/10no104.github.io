-- ============================================================================
-- MODULE: dining-party-guest-architecture.sql
-- ============================================================================

-- EHWA Party / Table / Guest architecture.
-- Run after:
--   1. dining-requests-schema.sql
--   2. dining-qr-sessions-schema.sql
--   3. dining-qr-table-assignment.sql
--
-- This migration preserves the existing live queue. Any currently active
-- QR/table session becomes a one-table active Party automatically.

create extension if not exists pgcrypto;

create table if not exists public.dining_parties (
  id bigint generated by default as identity primary key,
  branch text not null,
  status text not null default 'ACTIVE',
  created_at timestamptz not null default now(),
  closed_at timestamptz,
  closed_reason text not null default '',
  updated_at timestamptz not null default now(),
  constraint dining_parties_branch_check
    check (branch ~ '^[a-z0-9_-]{1,40}$'),
  constraint dining_parties_status_check
    check (status in ('ACTIVE', 'CLOSED', 'VOID')),
  constraint dining_parties_closed_check
    check (
      (status = 'ACTIVE' and closed_at is null)
      or
      (status in ('CLOSED', 'VOID') and closed_at is not null)
    )
);

create table if not exists public.dining_tables (
  id bigint generated by default as identity primary key,
  branch text not null,
  table_code text not null,
  qr_number integer,
  current_party_id bigint references public.dining_parties (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint dining_tables_branch_check
    check (branch ~ '^[a-z0-9_-]{1,40}$'),
  constraint dining_tables_code_check
    check (char_length(trim(table_code)) between 1 and 40),
  constraint dining_tables_qr_check
    check (qr_number is null or qr_number between 1 and 10),
  constraint dining_tables_branch_code_unique
    unique (branch, table_code)
);

create unique index if not exists dining_tables_branch_code_ci_unique
  on public.dining_tables (branch, lower(table_code));

create unique index if not exists dining_tables_branch_qr_unique
  on public.dining_tables (branch, qr_number)
  where qr_number is not null;

create index if not exists dining_tables_current_party_idx
  on public.dining_tables (current_party_id)
  where current_party_id is not null;

create table if not exists public.dining_party_tables (
  id bigint generated by default as identity primary key,
  party_id bigint not null references public.dining_parties (id) on delete restrict,
  table_id bigint not null references public.dining_tables (id) on delete restrict,
  joined_at timestamptz not null default now(),
  left_at timestamptz,
  constraint dining_party_tables_time_check
    check (left_at is null or left_at >= joined_at)
);

create unique index if not exists dining_party_tables_one_active_table
  on public.dining_party_tables (table_id)
  where left_at is null;

create index if not exists dining_party_tables_party_history_idx
  on public.dining_party_tables (party_id, joined_at desc);

create table if not exists public.dining_guests (
  id uuid primary key default gen_random_uuid(),
  branch text not null,
  display_code text not null,
  party_id bigint not null references public.dining_parties (id) on delete restrict,
  current_table_id bigint references public.dining_tables (id) on delete set null,
  status text not null default 'ACTIVE',
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '10 hours'),
  paid_at timestamptz,
  last_seen_at timestamptz not null default now(),
  current_page text not null default '',
  device_info jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  constraint dining_guests_branch_check
    check (branch ~ '^[a-z0-9_-]{1,40}$'),
  constraint dining_guests_display_code_check
    check (display_code ~ '^[A-Z2-9]{4,6}$'),
  constraint dining_guests_status_check
    check (status in ('ACTIVE', 'PAID', 'EXPIRED', 'VOID')),
  constraint dining_guests_device_info_check
    check (jsonb_typeof(device_info) = 'object'),
  constraint dining_guests_expiry_check
    check (expires_at > created_at),
  constraint dining_guests_paid_check
    check (
      (status = 'PAID' and paid_at is not null)
      or
      (status <> 'PAID')
    ),
  constraint dining_guests_branch_display_unique
    unique (branch, display_code)
);

create index if not exists dining_guests_party_status_idx
